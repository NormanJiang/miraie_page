export function translator(language) {
  const index = Math.max(
    0,
    languages.findIndex((item) => item.code === language),
  );
  return (key, params = {}) =>
    (messages[key]?.[index] ?? key).replace(
      /\{(\w+)\}/g,
      (match, name) => params[name] ?? match,
    );
}
